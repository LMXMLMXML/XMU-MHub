def collect_urls(cells: list[str], section: str) -> list[str]:
    """收集一行的网址：显式 http(s) 链接 + 反引号里的裸域名。

    "已停用 / 请勿使用 / 域名索引"章节只作为书面警告留在文档里，**不再收进目录**——
    否则用户点进去只会看到一个打不开的旧站（2026-09 精查后改）。
    """
    if any(k in section for k in SKIP_BARE_SECTIONS):
        return []
    urls: list[str] = []
    for cell in cells:
        urls.extend(URL_RE.findall(cell))
        for ticked in re.findall(r"`([^`]+)`", cell):
            value = ticked.strip()
            if BARE_DOMAIN_RE.match(value):
                urls.append("https://" + value)
    # 去重且保持顺序；显式 http 链接优先
    ordered = [u for u in urls if u.startswith("http://") or u.startswith("https://")]
    return list(dict.fromkeys(ordered))


def parse_table_rows(path: Path):
    """逐行扫描 Markdown 表格行，返回 (section, subsection, cells)。"""
    section = ""
    subsection = ""
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line.startswith("### "):
            subsection = clean(line[4:])
            continue
        if line.startswith("## "):
            section = clean(line[3:])
            subsection = ""
            continue
        if not line.startswith("|"):
            continue
        if set(line) <= set("|-: "):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 2:
            continue
        yield section, subsection, cells


