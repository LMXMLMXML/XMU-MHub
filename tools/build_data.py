def url_key(url: str) -> str:
    """用于判重的网址指纹：忽略 http/https、大小写、末尾斜杠与默认端口。

    之前只看完整字符串，于是 `http://lac.xmu.edu.cn` 和 `https://lac.xmu.edu.cn`
    被当成两个站点，"实验动物中心"就出现了两条。
    """
    key = re.sub(r"^https?://", "", (url or "").strip().lower())
    key = key.replace(":80/", "/").replace(":443/", "/")
    return key.rstrip("/")


def merge_entries(entries: list[dict]) -> list[dict]:
    """先合并重复：同一网址/同名只保留一份（取信息更全的那一行）。

    注意要**先合并、后分类**：早期版本在分类之后才把重复行 update 进来，
    结果重复行把已算好的 用途/对象 覆盖回关键词袋的脏标签（校园地图、网上展馆都栽在这）。
    """
    by_url: dict[str, dict] = {}
    by_name: dict[str, dict] = {}
    out: list[dict] = []
    for e in entries:
        if e["name"] in REMOVED_ENTRIES:
            continue        # 已确认失效的条目不进目录（原因见 REMOVED_ENTRIES）
        url = e["urls"][0] if e["urls"] else ""
        existing = (by_url.get(url_key(url)) if url else None) or by_name.get(e["name"])
        if existing is None:
            e["urls"] = list(dict.fromkeys(e["urls"]))
            out.append(e)
            if url:
                by_url[url_key(url)] = e
            by_name[e["name"]] = e
            continue
        # 合并：网址并集、入口提示取有的那个、原始文本取更长的
        existing["urls"] = list(dict.fromkeys(existing["urls"] + e["urls"]))
        if not existing.get("entry") and e.get("entry"):
            existing["entry"] = e["entry"]
        if len(e.get("rawText") or "") > len(existing.get("rawText") or ""):
            existing["rawText"] = e["rawText"]
        if not existing.get("desc") and e.get("desc"):
            existing["desc"] = e["desc"]
        for campus in e.get("campus") or []:
            if campus not in existing["campus"]:
                existing["campus"].append(campus)
    return out


def dedupe(entries: list[dict]) -> list[dict]:
    seen_name: dict[str, dict] = {}
    out: list[dict] = []
    for e in merge_entries(entries):
        key_name = e["name"]
        if key_name in seen_name:
            continue
        e["id"] = slugify(key_name) or f"item-{len(out)}"
        e["url"] = e["urls"][0] if e["urls"] else ""
        e["kindLabel"] = KIND_LABELS.get(e["kind"], e["kind"])
        e["platform"] = detect_platform(
            e["kind"],
            # 用原始行文本判端：简介里可能出现"不是手机小程序"这类反向描述
            f"{e.get('rawText', '')} {e['name']} {e['kindLabel']}",
        )
        e["platformLabel"] = PLATFORM_LABELS[e["platform"]]
        e["desc"] = fill_description(e)
        # 小程序没有网址时，必须给出"去哪儿找"的提示（否则用户点了只能复制名字，一脸茫然）
        if e["kind"] == "miniprogram" and not (e.get("entry") or "").strip():
            e["entry"] = "微信内搜索名称即可打开"
        apply_link_status(e)

        # ---- 分类收口：先判断条目"是什么"，再给标签 ----
        # 原来的做法是把一大袋关键词往"名称+说明"上套，于是出现
        # 「网上展馆→用途=出行」「校园地图→对象=教师」「所有部处→用途=办事」这类牛头不对马嘴。
