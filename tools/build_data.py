def parse_url_doc() -> list[dict]:
    entries: list[dict] = []
    for section, subsection, cells in parse_table_rows(URL_DOC):
        if section.startswith("速查"):
            # 速查表只是正文条目的摘录，若采纳会覆盖掉正文里更准确的分组与说明
            continue
        blob = " ".join(cells)
        urls = collect_urls(cells, f"{section} {subsection}")
        if not urls:
            continue
        name = clean(cells[0])
        if not name or name.isdigit():
            continue
        desc_parts = []
        for cell in cells[1:]:
            if URL_RE.search(cell):
                tail = URL_RE.sub("", cell).strip()
                if tail:
                    desc_parts.append(clean(tail))
                continue
            if clean(cell):
                desc_parts.append(clean(cell))
        desc = " ".join(dict.fromkeys(desc_parts))[:160]
        group = subsection or section.replace("、", " · ")
        haystack = f"{name} {desc} {group}"
        entries.append(
            {
                "name": name,
                "kind": "web",
                "urls": list(dict.fromkeys(urls)),
                "desc": desc,
                "group": group,
                "source": f"网址总集 · {section}",
                "rawText": blob,
                "campus": tag_by(CAMPUS_RULES, haystack) or ["通用"],
                "audience": tag_by(AUDIENCE_RULES, haystack) or ["全体"],
                "purpose": tag_by(PURPOSE_RULES, haystack) or ["其他"],
                "keywords": synonyms_for(name, desc, ""),
            }
        )
    return entries


