def detect_platform(kind: str, blob: str) -> str:
    # 先剔除"非小程序""不是小程序"这类否定表述，否则会被当成小程序
    raw = blob
    for word in NEGATIONS:
        raw = raw.replace(word, "")

    if kind == "workwechat":
        return "both"
    if kind in ("miniprogram", "wechat", "unionpay", "app", "thirdparty"):
        return "mobile"

    has_web = "网页" in raw or "电脑" in raw
    has_app = "APP" in raw or "支付宝" in raw or "小灵龙" in raw
    has_mp = "小程序" in raw or "公众号" in raw

    if kind == "web":
        return "both" if has_web and (has_mp or has_app) else "pc"

    # confuse：看表格里写的"真实类型"
    if "触摸屏" in raw or "馆内" in raw or "现场" in raw:
        return "offline"
    if "双端" in raw:
        return "both"
    if has_web and (has_app or has_mp):
        return "both"
    if has_web:
        return "pc"
    if has_mp or has_app:
        return "mobile"
    return "pc"


