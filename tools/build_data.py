def clean(text: str) -> str:
    text = BADGE_RE.sub("", text)
    text = MD_RE.sub("", text)
    text = text.replace("｜", " | ")
    return re.sub(r"\s+", " ", text).strip(" |·—-")


def slugify(text: str) -> str:
    text = clean(text)
    text = unicodedata.normalize("NFKC", text)
    return re.sub(r"[^0-9a-zA-Z\u4e00-\u9fff]+", "-", text).strip("-").lower()[:60]


def tag_by(rules, haystack: str) -> list[str]:
    tags: list[str] = []
    for keys, values in rules:
        if any(k.lower() in haystack.lower() for k in keys):
            for v in values:
                if v not in tags:
                    tags.append(v)
    return tags


def synonyms_for(name: str, desc: str, entry: str) -> list[str]:
    """只按条目自身的名称/说明/入口匹配同义词。

    早期版本把所属章节名也算进来，导致「就业」章节里所有条目都被塞进招聘关键词，
    出现「报销」搜出来华留学报名这类误召回。
    """
    haystack = f"{name} {entry}".lower()
    words: list[str] = []
    for key, extra in SYNONYMS.items():
        if key.lower() in haystack:
            for w in extra:
                if w not in words:
                    words.append(w)
    return words


