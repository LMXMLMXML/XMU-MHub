def apply_link_status(e: dict) -> None:
    """把"网址实测能不能打开、页面标题对不对"贴到条目上，前端据此显示提示。"""
    info = LINK_STATUS.get(e["name"])
    if not isinstance(info, dict):
        return
    e["linkStatus"] = info.get("status", 0)
    e["linkOk"] = info.get("status") == 200
    e["linkTitle"] = (info.get("title") or "")[:80]
    e["linkCheckedAt"] = LINK_CHECKED_AT
    similar = info.get("similar", 1)
    # 只有"有标题、且标题与条目名重合度很低"才算可疑；没标题的页面（纯 JS 系统）不算。
    # 阈值 0.35：更松会把"图书馆→知识资源港"这类站点改名也算进来，太吵。
    e["linkTitleMismatch"] = bool(info.get("title")) and isinstance(similar, (int, float)) and 0 <= similar < 0.35


